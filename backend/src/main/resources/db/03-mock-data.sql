-- ==================== 考勤模拟数据（动态日期）====================
-- 使用存储过程生成当前月份的考勤数据

DELIMITER $$

DROP PROCEDURE IF EXISTS generate_attendance_data$$

CREATE PROCEDURE generate_attendance_data()
BEGIN
    DECLARE v_current_date DATE;
    DECLARE v_month_start DATE;
    DECLARE v_today_date DATE;

    -- 获取今天日期和本月第一天
    SET v_today_date = CURDATE();
    SET v_month_start = DATE_FORMAT(v_today_date, '%Y-%m-01');
    SET v_current_date = v_month_start;

    -- 清理本月可能存在的旧数据
    DELETE FROM attendance WHERE attend_date >= v_month_start;

    -- 生成本月每个工作日的考勤数据（最多到今天）
    WHILE v_current_date <= v_today_date DO
        -- 跳过周末（周六=6, 周日=7）
        IF DAYOFWEEK(v_current_date) BETWEEN 2 AND 6 THEN
            -- 插入所有学生的正常出勤记录
            INSERT INTO attendance (student_id, attend_date, status)
            SELECT id, v_current_date, 1 FROM student WHERE id <= 90;

            -- 随机设置一些异常情况
            IF DAYOFMONTH(v_current_date) % 5 = 0 THEN
                UPDATE attendance SET status = 2, remark = '迟到'
                WHERE attend_date = v_current_date AND student_id IN (FLOOR(DAYOFMONTH(v_current_date) * 2) % 90 + 1);
            END IF;

            IF DAYOFMONTH(v_current_date) % 7 = 0 THEN
                UPDATE attendance SET status = 4, remark = '请假'
                WHERE attend_date = v_current_date AND student_id = (DAYOFMONTH(v_current_date) + 80) % 90 + 1;
            END IF;
        END IF;

        SET v_current_date = DATE_ADD(v_current_date, INTERVAL 1 DAY);
    END WHILE;

END$$

DELIMITER ;

-- 执行存储过程生成考勤数据
CALL generate_attendance_data();

-- 删除存储过程
DROP PROCEDURE IF EXISTS generate_attendance_data;

